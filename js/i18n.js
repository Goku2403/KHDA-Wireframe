  let lang = 'en';
  try { lang = localStorage.getItem(KEY) === 'ar' ? 'ar' : 'en'; } catch { /* ignore */ }

  function t(key, vars) {
    let s = (DICT[lang] && DICT[lang][key]) || DICT.en[key] || key;
    s = s.replace(/\[\[(!?)s(?::([a-z]+))?\]\]/g, (_m, neg, name) => {
      const n = Number(vars ? vars[name || 'n'] : NaN);
      const plural = n !== 1;
      return (neg ? !plural : plural) ? 's' : '';
    });
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.split('{' + k + '}').join(v);
    return s;
  }

  function apply(root) {
    const scope = root || document;
    scope.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = t(el.dataset.i18n); });
    scope.querySelectorAll('[data-i18n-ph]').forEach(el => { el.placeholder = t(el.dataset.i18nPh); });
    scope.querySelectorAll('[data-i18n-title]').forEach(el => { el.title = t(el.dataset.i18nTitle); });
    scope.querySelectorAll('[data-i18n-aria]').forEach(el => { el.setAttribute('aria-label', t(el.dataset.i18nAria)); });
  }

  function setLang(next) {
    lang = next === 'ar' ? 'ar' : 'en';
    try { localStorage.setItem(KEY, lang); } catch { /* ignore */ }
    location.reload();
  }

  function markup() {
    document.documentElement.lang = lang;
    document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
  }

  // ---------- toast available on every page ----------
  function escHtml(s) {
    return String(s == null ? '' : s).replace(/[&<>"']/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));
  }
  function khdaToast(kind, title, text) {
    const host = document.getElementById('toastHost');
    if (!host) return;
    const el = document.createElement('div');
    el.className = 'toast toast--' + kind;
    const icon = kind === 'success' ? '<path d="M20 6 9 17l-5-5"/>'
      : kind === 'error' ? '<circle cx="12" cy="12" r="9"/><path d="M12 8v4m0 4h.01"/>'
        : '<circle cx="12" cy="12" r="9"/><path d="M12 8h.01M11 12h1v4h1"/>';
    const color = kind === 'success' ? 'var(--success)' : kind === 'error' ? 'var(--error)' : 'var(--info)';
    el.innerHTML = '<svg width="18" height="18" viewBox="0 0 24 24" fill="none" stroke="' + color +
      '" stroke-width="2" style="margin-top:1px">' + icon + '</svg><div><div class="toast__title">' +
      escHtml(title) + '</div><div class="toast__text">' + escHtml(text) + '</div></div>';
    host.append(el);
    setTimeout(() => { el.style.transition = 'opacity .3s'; el.style.opacity = '0'; setTimeout(() => el.remove(), 300); }, 4200);
  }
  window.khdaToast = khdaToast;

  // ---------- portal header: language toggle and account menu ----------
  function wireHeader() {
    const langBtn = document.getElementById('langToggle');
    if (langBtn) {
      // the caption is always the language you would switch TO
      langBtn.setAttribute('lang', lang === 'ar' ? 'en' : 'ar');
      langBtn.addEventListener('click', () => setLang(lang === 'ar' ? 'en' : 'ar'));
    }

    const pill = document.getElementById('userPill');
    const menu = document.getElementById('userMenu');
    if (!pill || !menu) return;

    function close() {
      if (menu.hidden) return;
      menu.hidden = true;
      pill.setAttribute('aria-expanded', 'false');
    }
    function open() {
      menu.hidden = false;
      pill.setAttribute('aria-expanded', 'true');
      const first = menu.querySelector('button');
      if (first) first.focus();
    }

    pill.addEventListener('click', e => {
      e.stopPropagation();
      if (menu.hidden) open(); else close();
    });
    menu.addEventListener('click', e => e.stopPropagation());
    document.addEventListener('click', close);
    document.addEventListener('keydown', e => {
      if (e.key !== 'Escape' || menu.hidden) return;
      close();
      pill.focus();
    });

    const out = document.getElementById('btnLogout');
    if (out) out.addEventListener('click', () => {
      close();
      if (typeof window.khdaToast === 'function') window.khdaToast('info', t('user.signedOut'), t('user.signedOutText'));
      else alert(t('user.signedOut') + '\n' + t('user.signedOutText'));
    });
  }

